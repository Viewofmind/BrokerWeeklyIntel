"""
BrokerWeeklyIntel - Data Collection Layer
X/Twitter Connector (Advanced Implementation)

This connector is designed to capture high-signal conversations from X (Twitter),
with special emphasis on:
- Reactions to new feature launches
- Reports of software glitches and technical issues
- High-quality, attributable user quotes (especially from official broker threads)

Architecture:
- Primary mode: Agent-driven (recommended)
  The Grok agent calls x_keyword_search / x_semantic_search using queries generated by this connector,
  then feeds the results back via `ingest_x_posts()`.

- Fallback mode: Direct Twitter API v2 (when TWITTER_BEARER_TOKEN is configured)
  Uses tweepy for autonomous scheduled runs.

This design gives us the best of both worlds:
- Extremely powerful search when running inside the Grok environment (as proven in v2.1 reports)
- Functional autonomous collection when a bearer token is available.
"""

