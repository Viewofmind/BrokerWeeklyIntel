class XConnector(BaseConnector):
    """
    Advanced X/Twitter Connector optimized for broker intelligence.

    Key strengths:
    - Generates highly targeted queries (proven effective in v2.1 runs)
    - Excellent support for official thread reactions (Z-Connect, launch posts)
    - Strong focus on feature launches + technical friction
    - Clean integration with DataCollector + Normalizer via RawSearchResult
    """

    name = "x"

    def __init__(self, config: Optional[Dict[str, Any]] = None):
        super().__init__(config)
        self.bearer_token = self.config.get("bearer_token") or None
        self._tweepy_client = None

    # ------------------------------------------------------------------
    # Query Generation (Core Value - Use these from the Agent!)
    # ------------------------------------------------------------------
    @classmethod
    def get_keyword_queries(
        cls,
        broker: BrokerName,
        start_date: datetime,
        end_date: datetime,
        min_faves: int = 1,
    ) -> List[str]:
        """
        Returns a list of high-precision keyword queries optimized for this broker.

        These queries are designed to surface:
        - New feature reactions
        - Technical issues / glitches
        - Direct user quotes
        """
        config = BROKER_QUERY_CONFIGS.get(broker, {})
        handles = config.get("handles", [])
        keywords = config.get("keywords", [broker.lower()])
        feature_terms = config.get("feature_focus", [])
        glitch_terms = config.get("glitch_focus", [])

        date_filter = f"since:{start_date.strftime('%Y-%m-%d')} until:{end_date.strftime('%Y-%m-%d')}"

        queries = []

        # 1. Official handle + feature reactions
        for handle in handles:
            queries.append(f"@{handle} ({' OR '.join(feature_terms)}) {date_filter} min_faves:{min_faves}")

        # 2. Feature launch / reaction focused
        if feature_terms:
            feature_or = " OR ".join(feature_terms)
            queries.append(f"({broker} OR {' OR '.join(keywords)}) ({feature_or}) {date_filter} min_faves:{min_faves}")

        # 3. Technical issues / glitches (very important for v2.1)
        if glitch_terms:
            glitch_or = " OR ".join(glitch_terms)
            queries.append(f"({broker} OR {' OR '.join(keywords)}) ({glitch_or}) {date_filter} min_faves:{min_faves}")

        # 4. High-quality quote friendly searches (low min_faves but still useful)
        quote_query = f"({broker} OR {' OR '.join(keywords)}) (love OR hate OR frustrating OR \"finally\" OR \"still missing\" OR \"wish they had\") {date_filter}"
        queries.append(quote_query)

        return queries

    @classmethod
    def get_semantic_queries(cls, broker: BrokerName) -> List[str]:
        """
        Returns semantic search queries that work well with x_semantic_search.
        These are great for discovering nuanced reactions.
        """
        config = BROKER_QUERY_CONFIGS.get(broker, {})
        base = broker.lower()

        return [
            f"real user reactions to {base} new app features or updates",
            f"{base} app problems, crashes, lag, or good experiences",
            f"users complaining about {base} technical issues this week",
            f"positive feedback on {base} new features like terminal or fixed deposits",
        ]

    # ------------------------------------------------------------------
    # Ingestion from Agent Tools (Primary Recommended Path)
    # ------------------------------------------------------------------
    def ingest_x_posts(
        self,
        posts: List[Dict[str, Any]],
        broker: Optional[BrokerName] = None,
        source_label: str = "x_keyword_search",
    ) -> List[RawSearchResult]:
        """
        Convert results from the agent's x_keyword_search or x_semantic_search
        into RawSearchResult objects.

        This is the recommended way to use this connector when running inside Grok.
        """
        results: List[RawSearchResult] = []

        for post in posts:
            try:
                text = post.get("text", "") or post.get("full_text", "")
                url = post.get("url") or f"https://x.com/{post.get('author_username', 'user')}/status/{post.get('id')}"
                author = post.get("author_username") or post.get("author", {}).get("username")

                published_at = post.get("created_at") or post.get("timestamp")
                if isinstance(published_at, str):
                    published_at = datetime.fromisoformat(published_at.replace("Z", "+00:00"))
                elif not isinstance(published_at, datetime):
                    published_at = datetime.utcnow()

                engagement = (
                    post.get("public_metrics", {}).get("like_count", 0) or
                    post.get("favorite_count", 0) or
                    post.get("likes", 0)
                )

                detected_broker = broker or self._detect_broker_from_text(text)

                result = RawSearchResult(
                    source=f"x:{source_label}",
                    query=post.get("query", "agent_provided"),
                    broker=detected_broker,
                    platform="x",
                    raw_data={
                        "text": text,
                        "url": url,
                        "author": author,
                        "published_at": published_at.isoformat() if hasattr(published_at, "isoformat") else str(published_at),
                        "engagement": engagement,
                        "id": str(post.get("id", "")),
                        "conversation_id": str(post.get("conversation_id", "")),
                    },
                    metadata={
                        "is_reply": bool(post.get("in_reply_to_user_id")),
                        "retweet_count": post.get("public_metrics", {}).get("retweet_count", 0),
                        "quote_count": post.get("public_metrics", {}).get("quote_count", 0),
                    },
                )
                results.append(result)
            except Exception as e:
                self.logger.warning(f"Failed to ingest X post: {e}")
                continue

        self.logger.info(f"Ingested {len(results)} posts from X into RawSearchResult format")
        return results

    def _detect_broker_from_text(self, text: str) -> BrokerName:
        """Lightweight broker detection from post text."""
        text_lower = text.lower()
        for broker, config in BROKER_QUERY_CONFIGS.items():
            for kw in config.get("keywords", []):
                if kw.lower() in text_lower:
                    return broker  # type: ignore
        return "Zerodha"  # safe default

    # ------------------------------------------------------------------
    # Main Search Interface
    # ------------------------------------------------------------------
    async def search(
        self,
        brokers: List[BrokerName],
        start_date: datetime,
        end_date: datetime,
        limit_per_broker: int = 50,
        pre_fetched_posts: Optional[List[Dict[str, Any]]] = None,
    ) -> List[RawSearchResult]:
        """
        Main search method.

        Two modes supported:

        1. Agent-driven (recommended):
           Pass results from x_keyword_search / x_semantic_search via `pre_fetched_posts`.

        2. Autonomous (requires TWITTER_BEARER_TOKEN):
           Will attempt to use Twitter API v2 directly via tweepy.
        """
        if pre_fetched_posts:
            self.logger.info(f"XConnector using pre-fetched posts ({len(pre_fetched_posts)} total)")
            return self.ingest_x_posts(pre_fetched_posts)

        # Autonomous mode (if token available)
        if self.bearer_token:
            return await self._search_via_twitter_api(brokers, start_date, end_date, limit_per_broker)

        self.logger.warning(
            "XConnector.search called without pre_fetched_posts and no bearer token. "
            "Returning empty. Best results come from agent-driven collection."
        )
        return []

    async def _search_via_twitter_api(
        self,
        brokers: List[BrokerName],
        start_date: datetime,
        end_date: datetime,
        limit_per_broker: int,
    ) -> List[RawSearchResult]:
        """Autonomous collection using Twitter API v2 (requires bearer token)."""
        try:
            import tweepy
        except ImportError:
            self.logger.error("tweepy not installed. Cannot use autonomous X collection.")
            return []

        if not self._tweepy_client:
            self._tweepy_client = tweepy.Client(bearer_token=self.bearer_token, wait_on_rate_limit=True)

        all_results: List[RawSearchResult] = []

        for broker in brokers:
            queries = self.get_keyword_queries(broker, start_date, end_date, min_faves=2)

            for query in queries[:3]:  # Limit to avoid rate limits
                try:
                    tweets = self._tweepy_client.search_recent_tweets(
                        query=query,
                        max_results=min(20, limit_per_broker),
                        tweet_fields=["created_at", "public_metrics", "author_id", "conversation_id"],
                        expansions=["author_id"],
                    )

                    if tweets.data:
                        for tweet in tweets.data:
                            raw = RawSearchResult(
                                source="x:twitter_api_v2",
                                query=query,
                                broker=broker,
                                platform="x",
                                raw_data={
                                    "text": tweet.text,
                                    "url": f"https://x.com/i/web/status/{tweet.id}",
                                    "published_at": tweet.created_at.isoformat(),
                                    "engagement": tweet.public_metrics.get("like_count", 0) if tweet.public_metrics else 0,
                                    "id": str(tweet.id),
                                },
                            )
                            all_results.append(raw)
                except Exception as e:
                    self.logger.warning(f"Twitter API error for {broker}: {e}")

        return all_results

    # ------------------------------------------------------------------
    # Health & Diagnostics
    # ------------------------------------------------------------------
    async def health_check(self) -> Dict[str, Any]:
        """Report the current capability and configuration of the X connector."""
        has_bearer = bool(self.bearer_token)

        return {
            "status": "ready" if has_bearer else "agent_recommended",
            "connector": self.name,
            "autonomous_mode_available": has_bearer,
            "recommended_mode": "agent_driven",
            "capabilities": [
                "Excellent query generation for features + glitches",
                "Strong quote extraction from official threads",
                "Seamless ingestion of x_keyword_search + x_semantic_search results",
            ],
            "rate_limit_guidance": "Use min_faves:2+ and targeted queries. Prefer multiple small searches over one large query.",
            "example_usage": "See get_keyword_queries() and ingest_x_posts() methods",
        }

    async def close(self):
        """Cleanup (mainly for tweepy client if used)."""
        self._tweepy_client = None


# =============================================================================
# Convenience Factory + Documentation
# =============================================================================

def create_x_connector(bearer_token: Optional[str] = None) -> XConnector:
    """Create an XConnector, optionally with a bearer token for autonomous mode."""
    config = {}
    if bearer_token:
        config["bearer_token"] = bearer_token
    return XConnector(config=config)


